def muestraTipos():
    print("Tipos de datos en Python:")
    print(f"  El tipo de 4.2 es: {type(4.2)}")
    print(f"  El tipo de 'Hola Mundo' es: {type('Hola Mundo')}")
    print(f"  El tipo de True es: {type(True)}")
    print(f"  El tipo de 3 es: {type(3)}")  
    print(f" El tipo tupla es: {type((1, 2, 3))}")

def main():
    muestraTipos()

if __name__ == "__main__":
    main()
