#Definir una cadena
cadena = "45%"
#Dividir la cadena en partes utilizando el método split()
partes = cadena.split("%")
#Imprimir las partes resultantes
print(partes)
#tomar lo que esta antes del simbolo %
numero = partes[0]
print(numero)


