# Ejemplo de uso de operadores de aritmética en Python
def mostrar_operadores():

    # Suma
    suma = 5 + 3
    print("Suma: 5 + 3 =", suma)

    # Resta
    resta = 10 - 4
    print("Resta: 10 - 4 =", resta)

    # Multiplicación
    multiplicacion = 6 * 7
    print("Multiplicación: 6 * 7 =", multiplicacion)

    # Division Entera 
    division_entera = 10 // 3
    print("División Entera: 10 // 3 =", division_entera)

    # modulo
    modulo = 10 % 3
    print("Módulo: 10 % 3 =", modulo)

    # Potenciación
    potenciacion = 2 ** 3
    print("Potenciación: 2 ** 3 =", potenciacion)

def main():
    mostrar_operadores()

if __name__ == "__main__":
    main()
